#!/bin/bash
# Restore only into uniquely named disposable owned containers/volumes.
set -euo pipefail
test "$(id -u)" = 0
backup=${1:?Absolute owned backup directory required}
[[ "$backup" =~ ^/var/backups/student-marketplace-demo/[0-9]{8}T[0-9]{6}Z$ ]]
test -d "$backup" && test ! -L "$backup"
test "$(stat -c %u "$backup")" = 0
test "$(stat -c %a "$backup")" = 700
sha256sum --check --status "$backup/SHA256SUMS"
postgres=postgres:18.6-bookworm@sha256:5c4783a8cc3f0074912164f94dfa1be4e043438f0f707cf968d7af9a0d31a2c8
name="marketplace-restore-$(date -u +%Y%m%d%H%M%S)-$RANDOM"
volume="${name}-pg"
upload_volume="${name}-uploads"
umask 077
secret=$(mktemp /root/marketplace-restore-env.XXXXXX)
python3 -c 'import secrets; print("POSTGRES_PASSWORD="+secrets.token_hex(32)); print("POSTGRES_USER=marketplace\nPOSTGRES_DB=marketplace")' > "$secret"
cleanup() {
  docker rm -f "$name" >/dev/null 2>&1 || true
  docker volume rm "$volume" "$upload_volume" >/dev/null 2>&1 || true
  rm -f "$secret"
}
trap cleanup EXIT
docker volume create --label student-marketplace-owned=restore "$volume" >/dev/null
docker volume create --label student-marketplace-owned=restore "$upload_volume" >/dev/null
docker run --detach --name "$name" --network none --env-file "$secret" \
  --mount type=volume,source="$volume",target=/var/lib/postgresql \
  --memory 768m --cpus 0.5 --pids-limit 128 --log-driver json-file --log-opt max-size=5m --log-opt max-file=2 \
  "$postgres" >/dev/null
ready=false
for ((attempt=0; attempt<60; attempt++)); do
  if docker exec "$name" pg_isready -U marketplace -d marketplace >/dev/null 2>&1; then ready=true; break; fi
  sleep 1
done
test "$ready" = true
docker exec -i "$name" pg_restore --exit-on-error -U marketplace -d marketplace < "$backup/database.dump"
docker exec "$name" psql -v ON_ERROR_STOP=1 -U marketplace -d marketplace -Atc \
  "SELECT version_num FROM alembic_version; SELECT count(*) FROM users; SELECT count(*) FROM listings;"
image=$(cat "$backup/APP-IMAGE")
[[ "$image" =~ ^sha256:[a-f0-9]{64}$ ]]
# Extract only the archive generated by backup.sh, with explicit path/link checks.
docker run --rm --network none --read-only --cap-drop ALL --security-opt no-new-privileges \
  --user 0:0 --memory 256m --cpus 0.5 --pids-limit 32 \
  --mount type=volume,source="$upload_volume",target=/restore \
  --mount type=bind,source="$backup/uploads.tar",target=/backup.tar,readonly \
  "$image" python -c '
import hashlib,pathlib,tarfile
root=pathlib.Path("/restore")
with tarfile.open("/backup.tar") as archive:
    members=archive.getmembers()
    for member in members:
        if member.name.startswith("/") or ".." in pathlib.PurePosixPath(member.name).parts or not(member.isdir() or member.isfile()):
            raise SystemExit("Unsafe archive member")
    archive.extractall(root, members=members, filter="data")
    files=sorted(p for p in root.rglob("*") if p.is_file())
    for path in files:
        name=str(path.relative_to(root))
        original=archive.extractfile(name).read()
        if hashlib.sha256(path.read_bytes()).digest()!=hashlib.sha256(original).digest():
            raise SystemExit("Restored upload mismatch")
    print("Restored upload files:", len(files))'
echo 'Isolated backup restore succeeded; disposable owned targets removed on exit.'
